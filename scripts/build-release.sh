#!/bin/bash
# The only release build path. Every compiled-in path is rewritten to /build and symbols are
# stripped, so the DMG carries no local paths — the rule the public scan enforces
# (scripts/scan-public.sh). Paths come from the caller's own $HOME, never a committed absolute path.
#
# Sparkle is the one thing the Tauri bundler cannot place for us: the framework has to sit inside
# the .app before the app is signed, and its nested code signed first (INTEGRATION.md §3A/§3B). So
# this script builds the .app with the bundler, adds and signs Sparkle, then makes the DMG itself.
#
#   bash scripts/build-release.sh            # .app + DMG into dist/
#
# SUPublicEDKey comes from this app's own key file; the private half never enters the repo:
#   ~/.kh-sparkle/com.terranash.wirestudiokh/private.key   (or WIRE_SPARKLE_PRIVATE)
set -euo pipefail
export PATH="$HOME/.cargo/bin:$PATH"
cd "$(dirname "$0")/.."

step() { printf '\n==> %s\n' "$1"; }
fail() { printf '\nStopped: %s\n' "$1" >&2; exit 1; }

version="$(cat VERSION)"
name="Wire Studio KH"
app="src-tauri/target/release/bundle/macos/$name.app"
dmg_out="dist/${name}_${version}_aarch64.dmg"
vendor="src-tauri/vendor/khsparkle"

[ -f "$vendor/libkhsparkle.a" ] || fail "the vendored libkhsparkle.a is missing"
[ -d "$vendor/Sparkle.framework" ] || fail "the vendored Sparkle.framework is missing"

step "Checking versions agree"
grep -qx "version = \"$version\"" src-tauri/Cargo.toml || fail "Cargo.toml version differs from VERSION"
grep -q "\"version\": \"$version\"" src-tauri/tauri.conf.json || fail "tauri.conf.json version differs from VERSION"
[ "$(awk '/^## / { print $2; exit }' CHANGELOG.md)" = "$version" ] || fail "CHANGELOG.md's newest entry is not $version"
# app-meta.json is read by the feed generator at the tag; a stale localFile names the wrong artifact.
grep -q "\"localFile\": \"${name}_${version}_aarch64.dmg\"" app-meta.json \
  || fail "app-meta.json localFile does not name ${name}_${version}_aarch64.dmg — run scripts/set-app-meta-file.sh as part of the version bump, then commit"

step "Reading this app's Sparkle public key"
# The public half lives beside the private one and is not secret; it is still not committed, because
# until the key exists a committed value would be a guess. WIRE_SPARKLE_PUB may name it directly.
private_key="${WIRE_SPARKLE_PRIVATE:-$HOME/.kh-sparkle/com.terranash.wirestudiokh/private.key}"
pub_file="${WIRE_SPARKLE_PUB:-${private_key%.key}.pub}"
[ -f "$private_key" ] || fail "no Sparkle private key at $private_key — the build cannot sign or set SUPublicEDKey without it (set WIRE_SPARKLE_PRIVATE)"
chmod 600 "$private_key" 2>/dev/null || true
[ -f "$pub_file" ] || fail "no Sparkle public key at $pub_file — set WIRE_SPARKLE_PUB (44 base64 chars); a guessed key would brick every future update"
pub="$(tr -d '[:space:]' < "$pub_file")"
[ "${#pub}" -eq 44 ] || fail "SUPublicEDKey looks wrong (expected 44 base64 chars, got ${#pub})"
printf 'public key: %s…\n' "${pub:0:8}"

step "Building the release app bundle"
# Rust bakes absolute source paths (the cargo registry, this workspace) into panic metadata; remap
# them so the shipped binary carries no local path.
export RUSTFLAGS="--remap-path-prefix=$HOME=/build --remap-path-prefix=${TMPDIR:-/tmp}=/tmp"
npx tauri build --bundles app "$@" || fail "the release build failed"
[ -d "$app" ] || fail "no app bundle at $app"

step "Writing SUPublicEDKey into the bundle's Info.plist"
# The plist is generated by the bundler and merged with src-tauri/Info.plist; this is the build
# writing the one key that cannot live in the repo. It happens before signing, so the seal covers it.
/usr/libexec/PlistBuddy -c "Add :SUPublicEDKey string $pub" "$app/Contents/Info.plist" >/dev/null 2>&1 \
  || /usr/libexec/PlistBuddy -c "Set :SUPublicEDKey $pub" "$app/Contents/Info.plist" \
  || fail "could not write SUPublicEDKey into $app/Contents/Info.plist"

step "Copying and signing Sparkle (nested first, app last)"
mkdir -p "$app/Contents/Frameworks"
rm -rf "$app/Contents/Frameworks/Sparkle.framework"
cp -R "$vendor/Sparkle.framework" "$app/Contents/Frameworks/" \
  || fail "could not copy the vendored Sparkle.framework into Contents/Frameworks"
ID="KH Studio Local Signing"
FW="$app/Contents/Frameworks/Sparkle.framework/Versions/B"
for nested in "$FW/XPCServices/Downloader.xpc" "$FW/XPCServices/Installer.xpc" "$FW/Updater.app" "$FW/Autoupdate"; do
  [ -e "$nested" ] || fail "the vendored Sparkle framework has no $(basename "$nested")"
  codesign --force --sign "$ID" --timestamp=none --options runtime "$nested" \
    || fail "could not sign $(basename "$nested")"
done
codesign --force --sign "$ID" --timestamp=none --options runtime "$FW" \
  || fail "could not sign the Sparkle framework"
codesign --force --sign "$ID" --timestamp=none --options runtime "$app/Contents/MacOS/$name" \
  || fail "could not sign the binary"
codesign --force --sign "$ID" --timestamp=none --options runtime "$app" \
  || fail "could not sign the app"
codesign --verify --deep --strict "$app" || fail "the app's signature is broken"

step "Checking what the bundle carries"
python3 - "$app" "$version" <<'PY'
import plistlib, sys
app, version = sys.argv[1], sys.argv[2]
p = plistlib.load(open(app + "/Contents/Info.plist", "rb"))
assert p.get("CFBundleIdentifier") == "com.terranash.wirestudiokh", p.get("CFBundleIdentifier")
assert p.get("CFBundleShortVersionString") == version, p.get("CFBundleShortVersionString")
assert p.get("SUFeedURL") == "https://theng12.github.io/wire-studio-kh/appcast.xml", "SUFeedURL missing"
key = p.get("SUPublicEDKey") or ""
assert len(key) == 44, "SUPublicEDKey missing or wrong"
assert p.get("KHHoldURL", "").endswith(":8649/api/maintenance/hold"), "KHHoldURL missing"
assert p.get("KHHoldTokenFile", "").endswith("KHUpdater/hold-token"), "KHHoldTokenFile missing"
print("Info.plist: id, version, SUFeedURL, SUPublicEDKey, KHHoldURL, KHHoldTokenFile ok")
PY
otool -l "$app/Contents/MacOS/$name" | grep -q '@executable_path/../Frameworks' \
  || fail "the binary carries no @executable_path/../Frameworks rpath"
[ -d "$app/Contents/Frameworks/Sparkle.framework" ] || fail "the app carries no Sparkle.framework"

step "Packaging the DMG"
mkdir -p dist src-tauri/target/release/bundle/dmg
[ ! -e "$dmg_out" ] || fail "$dmg_out already exists; one version = one artifact, so choose a new version"
staging="$(mktemp -d "${TMPDIR:-/tmp}/wire-dmg-src.XXXXXX")"
trap 'rm -rf "$staging"' EXIT
ditto "$app" "$staging/$name.app"
ln -s /Applications "$staging/Applications"
dmg_source="src-tauri/target/release/bundle/dmg/${name}_${version}_aarch64.dmg"
rm -f "$dmg_source"
hdiutil create -volname "$name $version" -srcfolder "$staging" -format UDZO -ov "$dmg_source" >/dev/null \
  || fail "hdiutil could not build the DMG"
cp "$dmg_source" "$dmg_out"

step "Verifying the DMG"
mount="$(mktemp -d "${TMPDIR:-/tmp}/wire-dmg-mnt.XXXXXX")"
trap 'hdiutil detach "$mount" >/dev/null 2>&1 || true; rmdir "$mount" 2>/dev/null || true; rm -rf "$staging"' EXIT
hdiutil attach "$dmg_out" -nobrowse -readonly -mountpoint "$mount" >/dev/null || fail "the DMG does not mount"
codesign --verify --deep --strict "$mount/$name.app" || fail "the app inside the DMG failed its signature check"
[ -d "$mount/$name.app/Contents/Frameworks/Sparkle.framework" ] || fail "the DMG's app carries no Sparkle.framework"
hdiutil detach "$mount" >/dev/null
rmdir "$mount" 2>/dev/null || true
trap 'rm -rf "$staging"' EXIT

printf '\nRelease ready: %s (%s bytes, sha256 %s)\n' "$dmg_out" \
  "$(stat -f %z "$dmg_out")" "$(shasum -a 256 "$dmg_out" | awk '{print $1}')"
